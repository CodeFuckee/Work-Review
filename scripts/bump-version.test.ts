import test from 'node:test';
import assert from 'node:assert/strict';

import { spawnSync } from 'node:child_process';
import {
  existsSync,
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

// 版本自增：computeNextVersion 纯函数 + bump-version.mjs 对五个版本源的同步。
// 规则：末位 +1；末位逢 100 进位（中位 +1、末位归 0）；中位恰逢 100 再进位到首位。
const SCRIPT = fileURLToPath(new URL('./bump-version.mjs', import.meta.url));

// 直接加载脚本的纯函数导出（脚本用 export 便于测试；同时支持 CLI 调用）
let computeNextVersion: (current: string) => string | null;
try {
  ({ computeNextVersion } = await import('./bump-version.mjs'));
} catch {
  computeNextVersion = () => null; // 尚未实现
}

function fixtureRepo(t: test.TestContext): string {
  const dir = mkdtempSync(join(tmpdir(), 'work-review-bump-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ name: 'work-review', version: '1.2.99' }, null, 2), 'utf8');
  writeFileSync(
    join(dir, 'package-lock.json'),
    JSON.stringify({ name: 'work-review', version: '1.2.99', lockfileVersion: 3, packages: { '': { version: '1.2.99' } } }, null, 2),
    'utf8',
  );
  mkdirSync(join(dir, 'src-tauri'), { recursive: true });
  writeFileSync(join(dir, 'src-tauri', 'tauri.conf.json'), JSON.stringify({ version: '1.2.99' }, null, 2), 'utf8');
  writeFileSync(join(dir, 'src-tauri', 'Cargo.toml'), '[package]\nname = "work-review"\nversion = "1.2.99"\n', 'utf8');
  writeFileSync(
    join(dir, 'Cargo.lock'),
    '# This file is automatically @generated by Cargo.\n[[package]]\nname = "work-review"\nversion = "1.2.99"\n\n[[package]]\nname = "other"\nversion = "0.1.0"\n',
    'utf8',
  );
  return dir;
}

test('computeNextVersion 应末位自增', () => {
  assert.equal(computeNextVersion('1.2.3'), '1.2.4');
  assert.equal(computeNextVersion('0.0.0'), '0.0.1');
  assert.equal(computeNextVersion('1.1.9'), '1.1.10');
});

test('computeNextVersion 末位逢 100 应进位', () => {
  assert.equal(computeNextVersion('1.2.99'), '1.3.0');
  assert.equal(computeNextVersion('0.0.99'), '0.1.0');
  // 防御：输入已是 100 也应继续进位而非停在 100
  assert.equal(computeNextVersion('1.2.100'), '1.3.0');
});

test('computeNextVersion 中位逢 100 应继续进位', () => {
  // 1.99.99 → 中位 +1 后成 100 → 首位 +1
  assert.equal(computeNextVersion('1.99.99'), '2.0.0');
});

test('computeNextVersion 非法输入应返回 null', () => {
  assert.equal(computeNextVersion(''), null);
  assert.equal(computeNextVersion('abc'), null);
  assert.equal(computeNextVersion('1.2'), null);
  assert.equal(computeNextVersion('1.2.3.4'), null);
  assert.equal(computeNextVersion(' 1.2.3 '), null);
  assert.equal(computeNextVersion('1.2.x'), null);
});

test('bump-version.mjs dry-run 应只打印新版本不写文件', (t) => {
  const dir = fixtureRepo(t);
  const result = spawnSync(
    process.execPath,
    [SCRIPT, '--root', dir, '--dry-run'],
    { encoding: 'utf8' },
  );
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /1\.3\.0/);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  assert.equal(pkg.version, '1.2.99', 'dry-run 不得修改文件');
});

test('bump-version.mjs 应同步五个版本源并输出新版本', (t) => {
  const dir = fixtureRepo(t);
  const result = spawnSync(process.execPath, [SCRIPT, '--root', dir], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /1\.3\.0/);

  assert.equal(JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).version, '1.3.0');
  const lock = JSON.parse(readFileSync(join(dir, 'package-lock.json'), 'utf8'));
  assert.equal(lock.version, '1.3.0');
  assert.equal(lock.packages[''].version, '1.3.0');
  assert.equal(JSON.parse(readFileSync(join(dir, 'src-tauri', 'tauri.conf.json'), 'utf8')).version, '1.3.0');
  const cargo = readFileSync(join(dir, 'src-tauri', 'Cargo.toml'), 'utf8');
  assert.match(cargo, /^version\s*=\s*"1\.3\.0"/m);
  const cargoLock = readFileSync(join(dir, 'Cargo.lock'), 'utf8');
  assert.match(cargoLock, /\[\[package\]\]\s+name = "work-review"\s+version = "1\.3\.0"/);
  // 其它 package 的版本不得被改动
  assert.match(cargoLock, /\[\[package\]\]\s+name = "other"\s+version = "0\.1\.0"/);
});

test('bump-version.mjs 找不到版本源时应非零退出', (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'work-review-bump-empty-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const result = spawnSync(process.execPath, [SCRIPT, '--root', dir], { encoding: 'utf8' });
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /package\.json/);
});

test('永续性：每次 bump 后版本递增且可再次 bump（连续两次同步）', (t) => {
  const dir = fixtureRepo(t);
  const first = spawnSync(process.execPath, [SCRIPT, '--root', dir], { encoding: 'utf8' });
  assert.equal(first.status, 0, first.stderr);
  const second = spawnSync(process.execPath, [SCRIPT, '--root', dir], { encoding: 'utf8' });
  assert.equal(second.status, 0, second.stderr);
  assert.match(second.stdout, /1\.3\.1/);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  assert.equal(pkg.version, '1.3.1');
});
test('依赖恰好 pin 成当前版本号时不得被连坐升版', (t) => {
  const dir = fixtureRepo(t);
  const pkgPath = join(dir, 'package.json');
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  pkg.dependencies = { 'some-lib': '1.2.99' };
  writeFileSync(pkgPath, JSON.stringify(pkg, null, 2), 'utf8');

  const result = spawnSync(process.execPath, [SCRIPT, '--root', dir], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);

  const after = JSON.parse(readFileSync(pkgPath, 'utf8'));
  assert.equal(after.version, '1.3.0', '根级 version 应升版');
  assert.equal(
    after.dependencies['some-lib'],
    '1.2.99',
    '依赖恰好 pin 成旧版本号时必须原样保留（升它会造成与 lock 漂移）',
  );
});

test('任一版本源变换失败时零写入，不留半升版工作区', (t) => {
  const dir = fixtureRepo(t);
  rmSync(join(dir, 'Cargo.lock'));

  const result = spawnSync(process.execPath, [SCRIPT, '--root', dir], { encoding: 'utf8' });
  assert.notEqual(result.status, 0);

  // 旧实现在写 package.json 之后才轮到 Cargo.lock 抛错，会留下"1 新 4 旧"的
  // 半损坏态（本地没有 CI 的 reset --hard 兜底）；现在必须五个版本源全部保持旧版
  assert.equal(
    JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).version,
    '1.2.99',
    'package.json 不得被写入新版本',
  );
  assert.equal(
    JSON.parse(readFileSync(join(dir, 'src-tauri', 'tauri.conf.json'), 'utf8')).version,
    '1.2.99',
    'tauri.conf.json 不得被写入新版本',
  );
});
